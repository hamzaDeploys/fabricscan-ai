"""Procedurally drawn fabric images, used ONLY to smoke-test the pipeline end to end.

Every pixel here is generated by code: no photograph, public dataset or Kaggle data is involved. The images
are written to data/_smoke_test/ and must never be copied into dataset/ or used to train the submitted
model. Their only job is to prove that every script runs, and catches what it should catch, before the real
photos exist.

``generate_dataset`` also plants known faults (corrupt file, truncated JPEG, duplicates, label conflicts,
tiny image, EXIF-rotated photo, dark/blurry shots, ...) and returns what the cleaning step should report
for each one, so the smoke test can verify the cleaner instead of just running it.
"""

from __future__ import annotations

import datetime as dt
import shutil
from collections import Counter
from pathlib import Path
from typing import Sequence

import numpy as np
from PIL import Image, ImageDraw, ImageFilter

from .config import CLASS_NAMES
from .fsutils import prepare_output_dir

SURFACES = [(240, 238, 232), (28, 28, 30), (146, 104, 68), (58, 88, 150)]  # paper, dark cloth, wood, card
STAIN_COLOURS = [(92, 60, 24), (35, 35, 40), (150, 122, 40), (150, 40, 30)]  # coffee, ink, oil, ketchup


def _fabric(rng: np.random.Generator, h: int, w: int) -> np.ndarray:
    """Plain-weave texture with an optional stripe/check/dot print, lighting gradient, vignette and noise."""
    y, x = np.mgrid[0:h, 0:w].astype(np.float32)
    period = rng.uniform(3.0, 6.5)
    warp, weft = np.sin(2 * np.pi * x / period), np.sin(2 * np.pi * y / period)
    texture = 0.07 * warp * weft + 0.035 * (warp + weft)
    img = np.broadcast_to(rng.uniform(45, 215, size=3).astype(np.float32), (h, w, 3)).copy()
    pattern = rng.choice(["plain", "stripes", "checks", "dots"], p=[0.45, 0.25, 0.15, 0.15])
    accent = rng.uniform(30, 225, size=3).astype(np.float32)
    p = rng.uniform(24, 64)
    if pattern in ("stripes", "checks"):
        band = ((x / p) % 1.0) < rng.uniform(0.15, 0.4)
        if pattern == "checks":
            band |= ((y / p) % 1.0) < rng.uniform(0.15, 0.4)
        img[band] = 0.6 * img[band] + 0.4 * accent
    elif pattern == "dots":  # small printed dots: a "hard negative" that resembles tiny stains
        dots = ((x % p) - p / 2) ** 2 + ((y % p) - p / 2) ** 2 < (p * rng.uniform(0.08, 0.18)) ** 2
        img[dots] = 0.5 * img[dots] + 0.5 * accent
    img *= (1 + texture)[..., None]
    gx, gy = rng.uniform(-0.15, 0.15, size=2)
    xn, yn = x / w - 0.5, y / h - 0.5
    img *= (1 + gx * xn + gy * yn - 0.24 * (xn**2 + yn**2))[..., None]
    img += rng.normal(0, 2.5, size=img.shape)
    return np.clip(img, 0, 255)


def _blob(rng, h, w, cx, cy, radius, elongation=1.0, roughness=0.25) -> Image.Image:
    """Irregular closed shape as an 'L' mask."""
    theta = np.linspace(0, 2 * np.pi, 64, endpoint=False)
    r = np.ones_like(theta)
    for k in range(2, 6):
        r += roughness / k * np.sin(k * theta + rng.uniform(0, 2 * np.pi))
    angle = rng.uniform(0, np.pi)
    px, py = radius * r * np.cos(theta) * elongation, radius * r * np.sin(theta)
    xs = cx + px * np.cos(angle) - py * np.sin(angle)
    ys = cy + px * np.sin(angle) + py * np.cos(angle)
    mask = Image.new("L", (w, h), 0)
    ImageDraw.Draw(mask).polygon(list(zip(xs.tolist(), ys.tolist())), fill=255)
    return mask


def _soft(mask: Image.Image, blur: float) -> np.ndarray:
    return np.asarray(mask.filter(ImageFilter.GaussianBlur(blur)), dtype=np.float32) / 255.0


def _surface(rng) -> np.ndarray:
    return np.array(SURFACES[rng.integers(len(SURFACES))], np.float32)


def _hole(rng, img, cx, cy):
    h, w = img.shape[:2]
    mask = _blob(rng, h, w, cx, cy, rng.uniform(0.03, 0.09) * w, roughness=0.3)
    inner = _soft(mask, 1.0)[..., None]
    rim = np.clip(_soft(mask.filter(ImageFilter.MaxFilter(7)), 2.0)[..., None] - inner, 0, 1)
    img = img * (1 - 0.45 * rim)
    return img * (1 - inner) + _surface(rng) * inner


def _stain(rng, img, cx, cy):
    h, w = img.shape[:2]
    mask = _blob(rng, h, w, cx, cy, rng.uniform(0.05, 0.13) * w, roughness=0.4)
    a = rng.uniform(0.35, 0.7) * _soft(mask, rng.uniform(3, 10))[..., None]
    colour = np.array(STAIN_COLOURS[rng.integers(len(STAIN_COLOURS))], np.float32)
    out = img * (1 - a) + (img * 0.55 + colour * 0.45) * a
    if rng.random() < 0.5:  # dried "tide mark" ring at the edge
        ring = np.clip(_soft(mask, 1.5) - _soft(mask.filter(ImageFilter.MinFilter(5)), 1.5), 0, 1)
        out *= (1 - 0.25 * ring)[..., None]
    return out


def _broken_thread(rng, img, cx, cy):
    h, w = img.shape[:2]
    length, width = rng.uniform(0.25, 0.5) * w, int(rng.integers(2, 5))
    if rng.random() < 0.5:
        pts = [(cx - length / 2, cy), (cx + length / 2, cy)]
    else:
        pts = [(cx, cy - length / 2), (cx, cy + length / 2)]
    mask = Image.new("L", (w, h), 0)
    draw = ImageDraw.Draw(mask)
    draw.line([(float(a), float(b)) for a, b in pts], fill=255, width=width)
    ex, ey, r = float(pts[1][0]), float(pts[1][1]), rng.uniform(5, 12)  # pulled yarn loop at one end
    draw.arc([ex - r, ey - r, ex + r, ey + r], start=rng.uniform(0, 180), end=rng.uniform(200, 360), fill=255,
             width=2)
    m = _soft(mask, 0.7)[..., None]
    factor = rng.choice([0.65, 1.35])  # a missing yarn shows a dark gap; a pulled slub catches the light
    return img * (1 - m) + np.clip(img * factor, 0, 255) * m


def _wrinkle(rng, img):
    """Soft fold shading on defect-free fabric (a hard negative for broken threads)."""
    h, w = img.shape[:2]
    mask = Image.new("L", (w, h), 0)
    x0, y0, x1, y1 = rng.uniform(0, 1, 4) * [w, h, w, h]
    ImageDraw.Draw(mask).line([(x0, y0), (x1, y1)], fill=255, width=int(rng.integers(6, 16)))
    shade = _soft(mask, rng.uniform(6, 14))[..., None]
    return img * (1 + rng.choice([-0.14, 0.12]) * shade)


DEFECTS = {
    "hole": _hole,
    "stain": _stain,
    "broken_thread": _broken_thread,
}


def generate_sample(rng: np.random.Generator, class_name: str, size: int = 512,
                    width: int | None = None) -> np.ndarray:
    """One synthetic fabric image (float32 HxWx3) of the given class; the defect sits in the central area."""
    h, w = size, width or size
    img = _fabric(rng, h, w)
    side = min(h, w)
    cx = w / 2 + rng.uniform(-0.25, 0.25) * side
    cy = h / 2 + rng.uniform(-0.25, 0.25) * side
    if class_name == "good":
        if rng.random() < 0.5:
            img = _wrinkle(rng, img)
    else:
        img = DEFECTS[class_name](rng, img, cx, cy)
    return np.clip(img, 0, 255)


def _to_pil(arr: np.ndarray) -> Image.Image:
    return Image.fromarray(np.clip(arr, 0, 255).astype(np.uint8))


def _shots(rng, base: np.ndarray, n: int) -> list[Image.Image]:
    """The 4-shot recipe from the collection guide: as-is, rotated, warm indoor light, rotated + soft focus."""
    out = []
    for k in range(n):
        if k == 0:
            img = _to_pil(base)
        elif k == 1:
            img = _to_pil(np.rot90(base, 1))
        elif k == 2:
            img = _to_pil(base * np.array([1.08, 1.0, 0.82]) * rng.uniform(0.8, 0.9))
        elif k == 3:
            img = _to_pil(np.rot90(base, 2) + rng.normal(0, 4, base.shape)).filter(ImageFilter.GaussianBlur(0.7))
        else:
            img = _to_pil(np.fliplr(base) * rng.uniform(0.9, 1.1))
        out.append(img)
    return out


def _save_jpeg(img: Image.Image, path: Path, when: dt.datetime | None = None, orientation: int | None = None,
               quality: int = 92) -> None:
    exif = Image.Exif()
    if when is not None:
        exif[0x0132] = when.strftime("%Y:%m:%d %H:%M:%S")
    if orientation is not None:
        exif[0x0112] = orientation
    path.parent.mkdir(parents=True, exist_ok=True)
    img.save(path, "JPEG", quality=quality, exif=exif.tobytes())


def _inject_faults(rng, out: Path, first: dict[str, Path], size: int) -> dict[str, str]:
    """Plant known problems. Returns {relative path: expected reason prefix or flag}."""
    expected: dict[str, str] = {}

    def fresh(class_name: str, width: int | None = None) -> np.ndarray:
        return generate_sample(rng, class_name, size, width)

    target = out / "good/s001/zz_corrupt.jpg"
    target.write_bytes(rng.bytes(2048))
    expected["good/s001/zz_corrupt.jpg"] = "corrupt_or_unreadable"

    data = first["hole"].read_bytes()
    (out / "hole/s002").mkdir(parents=True, exist_ok=True)
    (out / "hole/s002/zz_truncated.jpg").write_bytes(data[: len(data) // 3])
    expected["hole/s002/zz_truncated.jpg"] = "corrupt_or_unreadable"

    (out / "stain/s003").mkdir(parents=True, exist_ok=True)
    shutil.copyfile(first["stain"], out / "stain/s003/zz_copy.jpg")
    expected["stain/s003/zz_copy.jpg"] = "exact_duplicate_of"

    with Image.open(first["good"]) as img:
        resaved = img.resize((int(img.width * 0.9), int(img.height * 0.9)), Image.Resampling.LANCZOS)
    _save_jpeg(resaved, out / "good/s008/zz_resaved.jpg", quality=70)
    expected["good/s008/zz_resaved.jpg"] = "near_duplicate_of"

    exact_twin = first["stain"].with_name("IMG_02.jpg")  # the same file in two classes: a labelling mistake
    (out / "good/s007").mkdir(parents=True, exist_ok=True)
    shutil.copyfile(exact_twin, out / "good/s007/zz_exact_conflict.jpg")
    expected["good/s007/zz_exact_conflict.jpg"] = "label_conflict_with"
    expected[exact_twin.relative_to(out).as_posix()] = "label_conflict_with"

    with Image.open(first["hole"]) as img:  # near-identical image in another class: flagged, not removed
        _save_jpeg(img.copy(), out / "stain/s005/zz_lookalike.jpg", quality=88)
    expected["stain/s005/zz_lookalike.jpg"] = "flag:check_label"
    expected[first["hole"].relative_to(out).as_posix()] = "flag:check_label"

    _save_jpeg(_to_pil(fresh("good")).resize((120, 120)), out / "good/s002/zz_tiny.jpg")
    expected["good/s002/zz_tiny.jpg"] = "too_small"

    (out / "good/s003").mkdir(parents=True, exist_ok=True)
    (out / "good/s003/notes.txt").write_text("not an image", encoding="utf-8")
    expected["good/s003/notes.txt"] = "unsupported_file_type"

    rgba = _to_pil(fresh("hole")).convert("RGBA")
    rgba.putalpha(Image.new("L", rgba.size, 230))
    (out / "hole/s003").mkdir(parents=True, exist_ok=True)
    rgba.save(out / "hole/s003/zz_alpha.png")
    expected["hole/s003/zz_alpha.png"] = "kept"

    _save_jpeg(_to_pil(fresh("stain")), out / "stain/s002/zz_rotated.jpg", orientation=6)
    expected["stain/s002/zz_rotated.jpg"] = "kept"

    _save_jpeg(_to_pil(fresh("good") * 0.12), out / "good/s004/zz_dark.jpg")
    expected["good/s004/zz_dark.jpg"] = "flag:too_dark"

    _save_jpeg(_to_pil(fresh("good")).filter(ImageFilter.GaussianBlur(8)), out / "good/s005/zz_blurry.jpg")
    expected["good/s005/zz_blurry.jpg"] = "flag:blurry"

    _save_jpeg(_to_pil(fresh("good", width=size * 4 // 3)), out / "good/s006/zz_wide.jpg")
    expected["good/s006/zz_wide.jpg"] = "flag:center_cropped"

    (out / "_rejected").mkdir(exist_ok=True)
    _save_jpeg(_to_pil(fresh("stain")), out / "_rejected/ambiguous.jpg")
    expected["_rejected/ambiguous.jpg"] = "ignored"
    return expected


def generate_dataset(
    out_dir: Path,
    samples_per_class: int = 12,
    shots: int = 4,
    size: int = 512,
    seed: int = 0,
    flat_classes: Sequence[str] = ("broken_thread",),
    inject_faults: bool = True,
    class_names: Sequence[str] = CLASS_NAMES,
) -> dict:
    """Write a raw-format synthetic dataset (same layout as dataset/) and return what was written.

    Classes in ``flat_classes`` are written without sample sub-folders, with EXIF capture times, to exercise
    the cleaner's time-based grouping.
    """
    out = prepare_output_dir(Path(out_dir))
    rng = np.random.default_rng(seed)
    clock = dt.datetime(2026, 1, 1, 9, 0, 0)
    written: Counter = Counter()
    first: dict[str, Path] = {}
    for class_name in class_names:
        for s in range(1, samples_per_class + 1):
            base = generate_sample(rng, class_name, size)
            for k, shot in enumerate(_shots(rng, base, shots)):
                if class_name in flat_classes:
                    path = out / class_name / f"IMG_{s:03d}_{k + 1}.jpg"
                else:
                    path = out / class_name / f"s{s:03d}" / f"IMG_{k + 1:02d}.jpg"
                _save_jpeg(shot, path, when=clock)
                first.setdefault(class_name, path)
                written[class_name] += 1
                clock += dt.timedelta(seconds=5)
            clock += dt.timedelta(minutes=2)  # time to prepare the next physical sample
    expected = _inject_faults(rng, out, first, size) if inject_faults else {}
    return {"images": dict(written), "expected": expected, "output_dir": str(out)}
